#!/usr/bin/env python3
"""
Compare old vs new PET/CT NIfTI outputs at the image-processing level.

  old : C:/Temp/PETCTSRC2   (previously generated)
  new : C:/Temp/PETCTSRC    (generated by petct_batch_pipeline.py)

Files are matched by relative path (e.g. G8V/G8V..._20261028/PET_G8V....nii.gz).
Only CT_*, SUV_*, PET_* NIfTI files are compared.

Comparison is done the way downstream code sees the data (SimpleITK ReadImage):
  - geometry : size, spacing, origin, direction
  - values   : after scl_slope/inter are applied (as ITK, nibabel get_fdata, Slicer do)
Header-only differences that do not change what ITK reads (qform/sform codes, descrip,
intent_name, raw-vs-scaled storage) are ignored on purpose.

Verdicts
  IDENTICAL          geometry equal (<=1e-6) and all voxel values bit-identical
  EQUIVALENT         geometry within --geom-tol and values within --atol/--rtol
  DIFF_GEOMETRY      size/spacing/origin/direction differ (voxel values not compared)
  DIFF_VALUES        same geometry, some voxels exceed tolerance
  ONLY_OLD/ONLY_NEW  file exists on one side only
  ERROR              could not read / compare

Usage
  python compare_petct_outputs.py
  python compare_petct_outputs.py --old C:/Temp/PETCTSRC2 --new C:/Temp/PETCTSRC --workers 4
"""
from __future__ import annotations

import argparse
import os
import re
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import numpy as np
import pandas as pd
import psutil
import SimpleITK as sitk
from tqdm import tqdm


def get_script_dir() -> Path:
    try:
        return Path(__file__).resolve().parent
    except NameError:
        return Path(sys.argv[0]).resolve().parent


SCRIPT_DIR   = get_script_dir()
DEFAULT_OLD  = Path("C:/Temp/PETCTSRC2")
DEFAULT_NEW  = Path("C:/Temp/PETCTSRC")
OUT_CSV      = SCRIPT_DIR.parent / "logs" / "compare_petctsrc.csv"
TARGET_RE    = re.compile(r"^(CT|SUV|PET)_.+\.nii(\.gz)?$")
CHUNK_SLICES = 32
GB = 1024 ** 3


def collect(root: Path) -> dict[str, Path]:
    out = {}
    for p in root.rglob("*"):
        if p.is_file() and TARGET_RE.match(p.name) and not p.name.startswith(".tmp_"):
            out[p.relative_to(root).as_posix()] = p
    return out


def kind_of(rel: str) -> str:
    return TARGET_RE.match(Path(rel).name).group(1)


def read3d(path: Path) -> sitk.Image:
    img = sitk.ReadImage(str(path))
    if img.GetDimension() == 4 and img.GetSize()[3] == 1:
        img = img[:, :, :, 0]
    if img.GetDimension() != 3:
        raise ValueError(f"{path.name}: {img.GetDimension()}D image")
    return img


def compare_pair(task) -> dict:
    rel, old_p, new_p, atol, rtol, geom_tol = task
    sitk.ProcessObject.SetGlobalDefaultNumberOfThreads(1)
    rec = {"rel_path": rel, "kind": kind_of(rel), "subject_dir": str(Path(rel).parent.as_posix())}

    if old_p is None:
        return {**rec, "verdict": "ONLY_NEW"}
    if new_p is None:
        return {**rec, "verdict": "ONLY_OLD"}

    try:
        a = read3d(old_p)
        b = read3d(new_p)
        rec.update({
            "old_type": a.GetPixelIDTypeAsString(), "new_type": b.GetPixelIDTypeAsString(),
            "old_size": "x".join(map(str, a.GetSize())), "new_size": "x".join(map(str, b.GetSize())),
            "old_spacing": ",".join(f"{v:.5f}" for v in a.GetSpacing()),
            "new_spacing": ",".join(f"{v:.5f}" for v in b.GetSpacing()),
        })

        d_sp = float(np.max(np.abs(np.subtract(a.GetSpacing(), b.GetSpacing()))))
        d_or = float(np.max(np.abs(np.subtract(a.GetOrigin(), b.GetOrigin()))))
        d_dir = float(np.max(np.abs(np.subtract(a.GetDirection(), b.GetDirection()))))
        rec.update({"max_spacing_diff": d_sp, "max_origin_diff_mm": d_or, "max_direction_diff": d_dir})

        geom_reasons = []
        if a.GetSize() != b.GetSize():
            geom_reasons.append("size")
        if d_sp > geom_tol:
            geom_reasons.append("spacing")
        if d_or > geom_tol:
            geom_reasons.append("origin")
        if d_dir > geom_tol:
            geom_reasons.append("direction")
        if geom_reasons:
            return {**rec, "verdict": "DIFF_GEOMETRY", "reason": ",".join(geom_reasons)}

        # Voxel comparison, chunked along z to bound memory; views avoid copying the volume
        va = sitk.GetArrayViewFromImage(a)   # (z, y, x)
        vb = sitk.GetArrayViewFromImage(b)
        nz = va.shape[0]
        exact = True
        n_bad = 0
        max_abs = 0.0
        sum_abs = 0.0
        max_rel = 0.0
        old_max = -np.inf
        new_max = -np.inf
        old_sum = 0.0
        new_sum = 0.0
        worst_idx = None
        n_total = va.size

        for z0 in range(0, nz, CHUNK_SLICES):
            ca = np.asarray(va[z0:z0 + CHUNK_SLICES], dtype=np.float64)
            cb = np.asarray(vb[z0:z0 + CHUNK_SLICES], dtype=np.float64)
            both_nan = np.isnan(ca) & np.isnan(cb)
            diff = np.abs(ca - cb)
            diff[both_nan] = 0.0
            if exact and not np.array_equal(ca[~both_nan], cb[~both_nan]):
                exact = False
            bad = ~(diff <= atol + rtol * np.abs(ca))   # NaN mismatch counts as bad
            n_bad += int(bad.sum())
            cmax = float(np.nanmax(diff)) if diff.size else 0.0
            if cmax > max_abs or np.isnan(cmax):
                max_abs = cmax
                flat = int(np.nanargmax(diff))
                zz, yy, xx = np.unravel_index(flat, diff.shape)
                worst_idx = (int(xx), int(yy), int(zz + z0))   # ITK index order (x, y, z)
            sum_abs += float(np.nansum(diff))
            denom = np.abs(ca)
            with np.errstate(divide="ignore", invalid="ignore"):
                r = np.where(denom > 1e-6, diff / denom, 0.0)
            max_rel = max(max_rel, float(np.nanmax(r)) if r.size else 0.0)
            old_max = max(old_max, float(np.nanmax(ca)))
            new_max = max(new_max, float(np.nanmax(cb)))
            old_sum += float(np.nansum(ca))
            new_sum += float(np.nansum(cb))

        rec.update({
            "max_abs_diff": max_abs,
            "mean_abs_diff": sum_abs / n_total,
            "max_rel_diff": max_rel,
            "n_voxels_over_tol": n_bad,
            "pct_voxels_over_tol": 100.0 * n_bad / n_total,
            "worst_voxel_xyz": "" if worst_idx is None else ",".join(map(str, worst_idx)),
            "old_max": old_max, "new_max": new_max,
            "old_mean": old_sum / n_total, "new_mean": new_sum / n_total,
        })

        notes = []
        if rec["old_type"] != rec["new_type"]:
            notes.append(f"pixel type {rec['old_type']} -> {rec['new_type']}")

        if exact and d_sp <= 1e-6 and d_or <= 1e-6 and d_dir <= 1e-6:
            verdict = "IDENTICAL"
        elif n_bad == 0:
            verdict = "EQUIVALENT"
        else:
            verdict = "DIFF_VALUES"
            notes.append(f"{n_bad} voxels over tolerance")
        return {**rec, "verdict": verdict, "reason": "; ".join(notes)}

    except Exception as e:
        return {**rec, "verdict": "ERROR", "reason": " ".join(str(e).split())[:300]}


def default_workers() -> int:
    # Two CT-grid volumes per task (~1-2 GB); keep headroom on a 32 GB machine
    phys = psutil.cpu_count(logical=False) or os.cpu_count() or 2
    avail_gb = psutil.virtual_memory().available / GB
    return max(1, min(4, phys - 2, int(avail_gb // 3)))


def main() -> None:
    ap = argparse.ArgumentParser(description="Compare old vs new PET/CT NIfTI outputs")
    ap.add_argument("--old", type=Path, default=DEFAULT_OLD, help=f"old root (default {DEFAULT_OLD})")
    ap.add_argument("--new", type=Path, default=DEFAULT_NEW, help=f"new root (default {DEFAULT_NEW})")
    ap.add_argument("--out", type=Path, default=OUT_CSV, help=f"result CSV (default {OUT_CSV})")
    ap.add_argument("--atol", type=float, default=1e-4, help="absolute tolerance (HU or SUV), default 1e-4")
    ap.add_argument("--rtol", type=float, default=1e-5, help="relative tolerance, default 1e-5")
    ap.add_argument("--geom-tol", type=float, default=1e-3, help="geometry tolerance (mm / cosine), default 1e-3")
    ap.add_argument("--workers", type=int, default=None)
    args = ap.parse_args()

    for root in (args.old, args.new):
        if not root.is_dir():
            sys.exit(f"[ERROR] Folder not found: {root}")

    old_files, new_files = collect(args.old), collect(args.new)
    keys = sorted(set(old_files) | set(new_files))
    if not keys:
        sys.exit("[ERROR] No CT_/SUV_/PET_ NIfTI files found in either folder")

    tasks = [(k, old_files.get(k), new_files.get(k), args.atol, args.rtol, args.geom_tol) for k in keys]
    n_workers = args.workers or default_workers()
    print(f"old: {len(old_files)} files | new: {len(new_files)} files | pairs: {len(keys)} | workers: {n_workers}")

    records = []
    with ProcessPoolExecutor(max_workers=n_workers) as ex:
        futs = {ex.submit(compare_pair, t): t[0] for t in tasks}
        with tqdm(total=len(futs), desc="Comparing", unit="file") as pbar:
            for f in as_completed(futs):
                try:
                    records.append(f.result())
                except Exception as e:
                    rel = futs[f]
                    records.append({"rel_path": rel, "kind": kind_of(rel), "verdict": "ERROR",
                                    "reason": " ".join(str(e).split())[:300]})
                pbar.update(1)

    df = pd.DataFrame(records).sort_values(["subject_dir", "kind"], na_position="last")
    first = ["rel_path", "kind", "verdict", "reason"]
    df = df[first + [c for c in df.columns if c not in first]]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(args.out, index=False)

    print("\n=== Summary (rows = file kind, columns = verdict) ===")
    print(pd.crosstab(df["kind"], df["verdict"], margins=True).to_string())

    bad = df[~df["verdict"].isin(["IDENTICAL", "EQUIVALENT"])]
    if len(bad):
        print(f"\n[!] {len(bad)} files not equivalent. First 15:")
        cols = [c for c in ["rel_path", "verdict", "reason", "old_size", "new_size", "max_abs_diff"] if c in bad.columns]
        print(bad[cols].head(15).to_string(index=False))
    else:
        print("\n[+] All files are identical or equivalent within tolerance.")
    print(f"\nDetails: {args.out}")


if __name__ == "__main__":
    main()
